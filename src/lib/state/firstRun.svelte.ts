/**
 * Состояние первого запуска.
 *
 * Живёт вне страницы: пустое состояние главной и похвала за первое действие
 * должны пережить переход на другой экран и обратно, а компонент страницы
 * при этом пересоздаётся.
 */
class FirstRunState {
	/**
	 * Данные дошли до экрана.
	 *
	 * Пустое хранилище сразу после запуска ещё ничего не значит: гидратация
	 * не закончилась, в разработке не отработал демо-сид, внутри Telegram
	 * не пришла первая синхронизация. Предлагать «начни с одного» до этого
	 * момента — значит мигнуть приглашением человеку с полной историей.
	 */
	settled = $state(false);

	/** Когда впервые за сессию показали пустую главную. */
	emptySince = $state<string | null>(null);

	/** Похвалу за первую запись закрыли. */
	praiseDismissed = $state(false);
}

export const firstRun = new FirstRunState();
