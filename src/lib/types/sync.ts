/**
 * Служебные поля синхронизируемой записи.
 *
 * Протокол оперирует строками с идентификатором и отметками времени: по ним
 * решается, что отправлять и чья версия победит при конфликте. Записи,
 * которые в интерфейсе выглядят частью документа — цели дня, бюджет дня, —
 * снаружи остаются такими же строками, поэтому эти поля им тоже нужны.
 */
export interface SyncMeta {
	/**
	 * Идентификатор записи.
	 *
	 * Случайный, а не производный от даты: id — первичный ключ на сервере,
	 * общий для всех пользователей, и «2026-09-20» у двух человек означало бы
	 * запись одного поверх записи другого.
	 */
	id: string;
	createdAt: string;
	updatedAt: string;
	/** Надгробие. Заполнено — запись удалена. */
	deletedAt?: string | null;
}
