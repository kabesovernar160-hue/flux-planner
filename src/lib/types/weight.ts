/**
 * Запись веса.
 *
 * Приложение считает цели от веса, но до сих пор не давало его отследить:
 * вес жил одним числом в анкете и молча устаревал. Между тем именно вес —
 * та метрика, ради которой дневник и ведут: калории это средство, а результат
 * человек видит на весах.
 *
 * Одна запись на день. Взвешиваются раз в сутки, и три значения за день
 * (до завтрака, после обеда, вечером) отличаются в основном содержимым
 * желудка — в графике это был бы шум, а не динамика.
 */
export interface WeightEntry {
	id: string;
	/** YYYY-MM-DD в часовом поясе пользователя. */
	date: string;
	weightKg: number;
	/** Короткая пометка: «после отпуска», «утром натощак». */
	note?: string;
	createdAt: string;
	updatedAt: string;
	/** Надгробие. Заполнено — запись удалена и не показывается. */
	deletedAt?: string | null;
}
